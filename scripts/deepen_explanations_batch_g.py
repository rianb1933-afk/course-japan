FILES = ['Kaigo-Hukum-Lanjut.html','Kaigo-Hukum.html','Kaigo-ICF-Assessment.html','Kaigo-Iijo-Ido.html','Kaigo-Infection-Control.html','Kaigo-Jinken-Fukushi.html']
VARNAME = {'Kaigo-Hukum-Lanjut.html':'Q','Kaigo-Hukum.html':'QKZ','Kaigo-ICF-Assessment.html':'Q',
           'Kaigo-Iijo-Ido.html':'Q','Kaigo-Infection-Control.html':'Q','Kaigo-Jinken-Fukushi.html':'Q'}
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

total_updated = 0
for fname in FILES:
    path = os.path.join(ROOT, 'Materi', fname)
    c = open(path, encoding='utf-8').read()
    m = re.search(r'var\s+' + VARNAME[fname] + r'\s*=\s*\[', c)
    start = m.end()-1
    depth=0; i=start; instr=False; esc=False
    while i < len(c):
        ch = c[i]
        if instr:
            if esc: esc=False
            elif ch=='\\': esc=True
            elif ch=='"': instr=False
        else:
            if ch=='"': instr=True
            elif ch=='[': depth+=1
            elif ch==']':
                depth-=1
                if depth==0: break
        i+=1
    end = i+1
    arr = json.loads(c[start:end])
    updated = 0
    for q in arr:
        if q['q'] in DEEP:
            q['e'] = DEEP[q['q']]
            updated += 1
    new_c = c[:start] + json.dumps(arr, ensure_ascii=False) + c[end:]
    open(path, 'w', encoding='utf-8').write(new_c)
    avg = sum(len(q['e']) for q in arr) / len(arr)
    short = sum(1 for q in arr if len(q['e'])<70)
    print(f"OK {fname}: {updated} diperbaiki, avg={avg:.0f}, masih pendek={short}")
    total_updated += updated

print(f"\nTOTAL: {total_updated} soal")
