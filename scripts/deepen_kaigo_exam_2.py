def main():
    for fname, extra in EXTRA.items():
        path = os.path.join(ROOT, 'Materi', fname)
        c = open(path, encoding='utf-8').read()
        m = re.search(r'var Q=(\[.*?\]);', c, re.DOTALL)
        if not m:
            print(f"FAIL {fname}"); continue
        Q = json.loads(m.group(1))
        existing = {q['q'] for q in Q}
        added = [e for e in extra if e['q'] not in existing]
        if not added:
            print(f"SKIP {fname}"); continue
        Q.extend(added)
        new_c = c[:m.start()] + 'var Q=' + json.dumps(Q, ensure_ascii=False) + ';' + c[m.end():]
        open(path, 'w', encoding='utf-8').write(new_c)
        print(f"OK   {fname}: +{len(added)} -> total {len(Q)}")

if __name__ == '__main__':
    main()
