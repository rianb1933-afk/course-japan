def js_vocab(vocab):
    return '[' + ', '.join(
        '[' + ', '.join('"' + x.replace('"', '\\"') + '"' for x in v) + ']'
        for v in vocab) + ']'


def main():
    c = open(TEMPLATE, encoding='utf-8').read()
    c = re.sub(r'<title>.*?</title>',
               f'<title>{TITLE} | Nihongo Pro Academy</title>', c, count=1)
    c = re.sub(r'(<meta name="description" content=")[^"]*(">)',
               lambda m: m.group(1) + DESC + m.group(2), c, count=1)
    c = c.replace('Kaigo-Ujian-N2.html', SLUG)
    c = re.sub(r'(<meta property="og:title" content=")[^"]*(">)',
               lambda m: m.group(1) + TITLE + ' — Nihongo Pro Academy' + m.group(2),
               c, count=1)
    c = re.sub(r'PH_VOCAB=\[.*?\];', 'PH_VOCAB=' + js_vocab(VOCAB) + ';',
               c, count=1, flags=re.DOTALL)
    c = re.sub(r'var Q=\[.*?\];',
               'var Q=' + json.dumps(QUESTIONS, ensure_ascii=False) + ';',
               c, count=1, flags=re.DOTALL)
    out = os.path.join(ROOT, 'Materi', SLUG)
    with open(out, 'w', encoding='utf-8') as f:
        f.write(c)
    print(f"✅ {SLUG}: {len(QUESTIONS)} soal kasus, {len(VOCAB)} kosakata (5 事例)")


if __name__ == '__main__':
    main()
