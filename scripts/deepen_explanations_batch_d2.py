VARNAME = {
 'Kaigo-Alzheimer-Lanjut.html':'Q','Kaigo-Alzheimer.html':'Q','Kaigo-Dementia-Communication.html':'Q',
 'Kaigo-Diabetes-Care.html':'Q','Kaigo-Dokumentasi.html':'Q','Kaigo-Fukushishi-Overview.html':'QKZ',
}
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

total_updated = 0
for fname in FILES:
    path = os.path.join(ROOT, 'Materi', fname)
    c = open(path, encoding='utf-8').read()
    varname = VARNAME[fname]
    m = re.search(r'var\s+' + varname + r'\s*=\s*\[', c)
    start = m.end()-1
    depth=0; i=start; instr=False; esc=False
    while i < len(c):
        ch = c[i]
        if instr:
            if esc: esc=False
            elif ch=='\\': esc=True
            elif ch=='"': instr=False
        else:
            if ch=='"': instr=True
            elif ch=='[': depth+=1
            elif ch==']':
                depth-=1
                if depth==0: break
        i+=1
    end = i+1
    arr = json.loads(c[start:end])
    updated = 0
    for q in arr:
        if q['q'] in DEEP:
            q['e'] = DEEP[q['q']]
            updated += 1
    new_c = c[:start] + json.dumps(arr, ensure_ascii=False) + c[end:]
    open(path, 'w', encoding='utf-8').write(new_c)
    avg = sum(len(q['e']) for q in arr) / len(arr)
    print(f"OK {fname}: {updated} diperbaiki, avg={avg:.0f} karakter")
    total_updated += updated

print(f"\nTOTAL: {total_updated} soal")
