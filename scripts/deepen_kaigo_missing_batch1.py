def extract_array_span(c, varname):
    m = re.search(r'var\s+' + varname + r'\s*=\s*\[', c)
    if not m: return None, None
    start = m.end() - 1
    depth=0; i=start; instr=False; esc=False
    while i < len(c):
        ch = c[i]
        if instr:
            if esc: esc=False
            elif ch=='\\': esc=True
            elif ch=='"': instr=False
        else:
            if ch=='"': instr=True
            elif ch=='[': depth+=1
            elif ch==']':
                depth-=1
                if depth==0: return start, i+1
        i+=1
    return None, None

def main():
    for fname, extra in EXTRA.items():
        path = os.path.join(ROOT, 'Materi', fname)
        c = open(path, encoding='utf-8').read()
        varname = VARNAME[fname]
        start, end = extract_array_span(c, varname)
        if start is None:
            print(f"FAIL {fname}: array {varname} tak ketemu"); continue
        arr = json.loads(c[start:end])
        existing = {q['q'] for q in arr}
        added = [e for e in extra if e['q'] not in existing]
        if not added:
            print(f"SKIP {fname}"); continue
        arr.extend(added)
        new_c = c[:start] + json.dumps(arr, ensure_ascii=False) + c[end:]
        open(path, 'w', encoding='utf-8').write(new_c)
        print(f"OK {fname} ({varname}): +{len(added)} -> {len(arr)}")

if __name__ == '__main__':
    main()
