def main():
    for fn, extra in EXTRA.items():
        p = os.path.join(ROOT,'Materi',fn)
        c = open(p,encoding='utf-8').read()
        m = re.search(r'var Q=(\[.*?\]);', c, re.DOTALL)
        if not m: print('FAIL',fn); continue
        Q = json.loads(m.group(1))
        existing = {q['q'] for q in Q}
        added = [e for e in extra if e['q'] not in existing]
        if not added: print('SKIP',fn); continue
        Q.extend(added)
        c = c[:m.start()]+'var Q='+json.dumps(Q,ensure_ascii=False)+';'+c[m.end():]
        open(p,'w',encoding='utf-8').write(c)
        print(f'OK {fn}: +{len(added)} -> {len(Q)}')

if __name__=='__main__': main()
