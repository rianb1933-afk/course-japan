def extract_span(c, varname):
    m = re.search(r'var\s+' + varname + r'\s*=\s*\[', c)
    if not m: return None, None
    start = m.end() - 1
    depth=0; i=start; instr=False; esc=False
    while i < len(c):
        ch = c[i]
        if instr:
            if esc: esc=False
            elif ch=='\\': esc=True
            elif ch=='"': instr=False
        else:
            if ch=='"': instr=True
            elif ch=='[': depth+=1
            elif ch==']':
                depth-=1
                if depth==0: return start, i+1
        i+=1
    return None, None

